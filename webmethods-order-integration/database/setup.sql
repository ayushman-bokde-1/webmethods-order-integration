  SELECT
    p.PRODUCT_ID,
    p.PRODUCT_NAME,
    p.UNIT_PRICE,
    p.CATEGORY,
    i.INVENTORY_ID,
    i.QUANTITY                            AS TOTAL_QUANTITY,
    i.WAREHOUSE,
    COALESCE(r.RESERVED_QTY, 0)          AS RESERVED_QUANTITY,
    i.QUANTITY - COALESCE(r.RESERVED_QTY, 0) AS AVAILABLE_QUANTITY
FROM
    PRODUCTS p
    JOIN INVENTORY i ON p.PRODUCT_ID = i.PRODUCT_ID
    LEFT JOIN (
        SELECT PRODUCT_ID, SUM(QUANTITY) AS RESERVED_QTY
        FROM INVENTORY_RESERVATIONS
        WHERE STATUS = 'RESERVED'
        GROUP BY PRODUCT_ID
    ) r ON p.PRODUCT_ID = r.PRODUCT_ID
