        ORDER_ID,
        PRODUCT_ID,
        QUANTITY,
        STATUS
    )
    SELECT 
        'RES-' || seq_reservation_id.NEXTVAL,
        p_order_id,
        PRODUCT_ID,
        p_quantity,
        'RESERVED'
    FROM VW_AVAILABLE_INVENTORY
    WHERE PRODUCT_ID = p_product_id
    AND AVAILABLE_QUANTITY >= p_quantity;

    p_rows_affected := SQL%ROWCOUNT;

    COMMIT;
END;

